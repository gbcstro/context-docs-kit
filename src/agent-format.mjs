import fs from 'node:fs';
import path from 'node:path';

/**
 * Persona agents are authored once, as Claude Code markdown (agents/*.md):
 * YAML frontmatter (name, description, tools, ...) and a markdown body.
 *
 * Codex defines custom agents as standalone TOML files in ~/.codex/agents/ or
 * <repo>/.codex/agents/, with required `name`, `description` and
 * `developer_instructions`. This module renders one from the other so the
 * personas never exist in two hand-maintained copies.
 */

/** Split an agent markdown file into flat frontmatter fields and the body. */
export function parseAgentMarkdown(raw) {
  const text = raw.replace(/\r\n/g, '\n');
  const match = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!match) throw new Error('agent file has no frontmatter');

  const fields = {};
  for (const line of match[1].split('\n')) {
    const i = line.indexOf(':');
    if (i <= 0) continue;
    fields[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  if (!fields.name || !fields.description) throw new Error('agent frontmatter needs name and description');
  return { fields, body: match[2].trim() };
}

/**
 * Codex custom agents inherit the parent's tools, so the frontmatter's `tools:`
 * allow-list becomes an instruction instead. It matters most for the critic,
 * whose independence depends on never editing the draft it reviews.
 */
function toolsInstruction(tools) {
  if (!tools) return '';
  const list = tools.split(',').map((t) => t.trim().toLowerCase());
  if (!list.includes('write') && !list.includes('edit')) {
    return 'You are read-only: read and search files and report. Never create, edit, or delete a file.\n\n';
  }
  return 'Read and search the repo freely, but write only the file your task names. Do not edit any other file.\n\n';
}

const tomlBasic = (s) =>
  `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\t/g, '\\t')}"`;

// Multi-line basic string: escape backslashes, and break any run of three quotes.
const tomlMultiline = (s) => `"""\n${s.replace(/\\/g, '\\\\').replace(/"""/g, '""\\"')}\n"""`;

/** Render a Codex custom-agent TOML file from agent markdown. */
export function renderCodexAgent(raw) {
  const { fields, body } = parseAgentMarkdown(raw);
  return [
    `# Generated by context-docs-kit from agents/${fields.name}.md. Edit the markdown, not this file.`,
    `name = ${tomlBasic(fields.name)}`,
    `description = ${tomlBasic(fields.description)}`,
    `developer_instructions = ${tomlMultiline(toolsInstruction(fields.tools) + body)}`,
    '',
  ].join('\n');
}

/** Agent file formats, keyed by TARGETS[*].agentFormat. */
export const AGENT_FORMATS = {
  md: { ext: '.md', render: (raw) => raw },
  toml: { ext: '.toml', render: renderCodexAgent },
};

/** The installed filename and rendered content for one shipped agent file. */
export function renderAgentFile(srcPath, format = 'md') {
  const fmt = AGENT_FORMATS[format];
  if (!fmt) throw new Error(`unknown agent format: ${format}`);
  return {
    file: path.basename(srcPath, '.md') + fmt.ext,
    content: fmt.render(fs.readFileSync(srcPath, 'utf8')),
  };
}
